"""Generate the small API contract directly from FastAPI OpenAPI, without npm tooling."""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        value = schema["const"]
        return (
            "'" + value.replace("'", "\\'") + "'" if isinstance(value, str) else json.dumps(value)
        )
    if "enum" in schema:
        return " | ".join(ts_type({"const": item}) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(item) for item in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        additional = schema.get("additionalProperties")
        value_type = ts_type(additional) if isinstance(additional, dict) else "unknown"
        return f"Record<string, {value_type}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate() -> str:
    from app.core.config import Settings
    from app.main import create_app

    schemas = create_app(Settings(_env_file=None)).openapi()["components"]["schemas"]
    lines = ["// Generated by scripts/generate_api_types.py. Do not edit manually.", ""]
    for name, schema in sorted(schemas.items()):
        if schema.get("type") != "object" or "properties" not in schema:
            lines.extend([f"export type {name} = {ts_type(schema)}", ""])
            continue
        lines.append(f"export interface {name} {{")
        required = schema.get("required", [])
        for field, value in schema["properties"].items():
            optional = "" if field in required else "?"
            field_type = ts_type(value)
            declaration = f"  {field}{optional}: {field_type}"
            if len(declaration) > 100 and "enum" in value:
                lines.append(f"  {field}{optional}:")
                lines.extend(f"    | {ts_type({'const': item})}" for item in value["enum"])
            else:
                lines.append(declaration)
        lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "frontend" / "src" / "types" / "schema.generated.ts"
    source = generate()
    if args.check:
        if not target.is_file() or target.read_text("utf-8") != source:
            parser.exit(1, "API 类型已过期，请运行 python scripts/generate_api_types.py。\n")
    else:
        target.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
